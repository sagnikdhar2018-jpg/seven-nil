export const ALL_PLAYERS: Player[] = SQUADS.flatMap((s) => s.players);

export function playersForSide(label: string, pool: PoolId = "world"): Player[] {
  const list = pool === "club" ? CLUB_PLAYERS : ALL_PLAYERS;
  const raw = label.replace(/\s+(19|20)\d{2}$/, "").trim().toLowerCase();
  const aliases: Record<string, string> = {
    united: "manchester united",
    city: "manchester city",
    bayern: "bayern munich",
    milan: "ac milan",
    dortmund: "borussia dortmund",
    atlético: "atlético madrid",
    atletico: "atlético madrid",
    leverkusen: "bayer leverkusen",
  };
  const key = aliases[raw] ?? raw;
  return list.filter((player) => player.nation.toLowerCase() === key);
}

export function randomSquad(excludeIds: string[] = [], pool: PoolId = "world"): Squad {
  if (pool === "club") return randomClubSquad(excludeIds);
  const filtered = SQUADS.filter((s) => !excludeIds.includes(s.id));
  const source = filtered.length ? filtered : SQUADS;
  return source[Math.floor(Math.random() * source.length)]!;
}

export function otherYears(squad: Squad, excludeIds: string[] = [], pool: PoolId = "world"): Squad[] {
  const list = pool === "club" ? CLUB_SQUADS : SQUADS;
  return list.filter(
    (s) => s.nation === squad.nation && s.id !== squad.id && !excludeIds.includes(s.id),
  );
}

