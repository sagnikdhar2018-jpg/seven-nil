import type { Player, Pos, Squad } from "./types";

type Raw = [string, number, Pos[], number];

function club(name: string, year: number, league: string, rows: Raw[]): Squad {
  const id = `${name}-${year}`;
  const used = new Set<number>();
  const seen = new Set<string>();
  return {
    id,
    nation: name,
    year,
    league,
    players: rows.map(([pname, num, pos, ovr], i) => {
      let n = num;
      while (used.has(n)) n += 1;
      used.add(n);
      let pid = `${id}-${n}-${pname}`;
      if (seen.has(pid)) pid = `${pid}-${i}`;
      seen.add(pid);
      return {
        id: pid,
        name: pname,
        nation: name,
        year,
        num: n,
        pos,
        ovr,
      };
    }),
  };
}

